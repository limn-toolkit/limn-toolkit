"""The licence of every source file a meson build compiled, read from its compile_commands.json.

Counts per licence, then lists every file that is not plainly MIT, so the build that is shipped
is the build that was read. A file is classified by its SPDX identifier when it carries one and
otherwise by the licence text in its first lines. Headers are not followed, and the files the
build generated itself are counted apart.

    python license_inventory.py <build dir> <source dir>
"""
import collections
import json
import os
import re
import sys

TEXTS = [
    ("GPL", re.compile(r"GNU (Lesser )?General Public License", re.I)),
    ("Apache-2.0", re.compile(r"Apache License", re.I)),
    ("BSL-1.0", re.compile(r"Boost Software License", re.I)),
    ("SGI-B-2.0", re.compile(r"SGI FREE SOFTWARE LICENSE B", re.I)),
    ("Zlib", re.compile(r"This software is provided 'as-is'", re.I)),
    ("MIT", re.compile(r"Permission is hereby granted,?\s+free of charge", re.I)),
    ("BSD", re.compile(r"Redistribution and use in source and binary forms", re.I)),
    ("public-domain", re.compile(r"public domain", re.I)),
]
SPDX = re.compile(r"SPDX-License-Identifier:\s*([^\s*/]+(?:\s+(?:OR|AND|WITH)\s+[^\s*/]+)*)")


def classify(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            head = "".join(f.readline() for _ in range(80))
    except OSError:
        return "unreadable"
    spdx = SPDX.search(head)
    if spdx:
        return spdx.group(1)
    flat = re.sub(r"[\s*/#]+", " ", head)
    for name, pattern in TEXTS:
        if pattern.search(flat):
            return name
    return "unknown"


def main(build_dir, source_dir):
    with open(os.path.join(build_dir, "compile_commands.json"), encoding="utf-8") as f:
        entries = json.load(f)
    build = os.path.realpath(build_dir)
    counts = collections.Counter()
    notable = []
    seen = set()
    for entry in entries:
        path = os.path.realpath(os.path.join(entry["directory"], entry["file"]))
        if path in seen:
            continue
        seen.add(path)
        if path.startswith(build):
            counts["generated by the build"] += 1
            continue
        licence = classify(path)
        counts[licence] += 1
        if licence != "MIT":
            notable.append((licence, os.path.relpath(path, source_dir)))
    print(f"{len(seen)} source files compiled")
    for licence, count in counts.most_common():
        print(f"{count:6d}  {licence}")
    print()
    print("Every file that is not plainly MIT:")
    for licence, path in sorted(notable):
        print(f"  {licence:24s} {path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
